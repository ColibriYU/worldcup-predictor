def build_hexagrams() -> list[dict[str, object]]:
    return [
        {
            "number": number,
            "name": name,
            "upper": upper,
            "lower": lower,
            "element": TRIGRAM_ELEMENTS[upper],
            "keywords": keywords,
            "explanation": explanation,
            "score": score,
        }
        for number, name, upper, lower, keywords, explanation, score in HEXAGRAMS
    ]


def build_tarot_cards() -> list[dict[str, object]]:
    cards: list[dict[str, object]] = []
    for number, (name, upright, reversed_keywords, interpretation, score) in enumerate(MAJOR_ARCANA):
        upright_text = "、".join(upright)
        reversed_text = "、".join(reversed_keywords)
        cards.append(
            {
                "arcana": "major",
                "number": number,
                "name": name,
                "upright_keywords": upright,
                "reversed_keywords": reversed_keywords,
                "meaning": interpretation,
                "upright_meaning": f"正位强调{upright_text}，在比赛叙事里通常代表这一能量可以顺畅表达。",
                "reversed_meaning": f"逆位强调{reversed_text}，在比赛叙事里通常代表这股能量被压住、走偏或需要付出代价。",
                "match_context": "用于补充赛前报告的心理、节奏和临场叙事，不修正任何胜平负概率。",
                "interpretation": interpretation,
                "score": score,
            }
        )

    for suit, config in SUITS.items():
        for rank, rank_score, rank_theme in MINOR_RANKS:
            cards.append(
                {
                    "arcana": "minor",
                    "suit": suit,
                    "element": config["element"],
                    "rank": rank,
                    "name": f"{suit}{rank}",
                    "upright_keywords": [rank_theme, *config["upright"]],
                    "reversed_keywords": [rank_theme, *config["reversed"]],
                    "meaning": f"{suit}{rank}关注{rank_theme}，并把重点落在{config['theme']}。",
                    "upright_meaning": f"正位时，{rank_theme}会帮助球队把{config['theme']}转化为更清晰的场面表达。",
                    "reversed_meaning": f"逆位时，{rank_theme}容易变成负担，使{config['theme']}出现迟滞、误读或过度消耗。",
                    "match_context": "用于描述比赛的情绪、节奏、执行与关键阶段走向，不进入量化模型。",
                    "interpretation": f"这张牌强调{config['theme']}，比赛解读重点放在{rank_theme}。",
                    "score": round(config["score"] + rank_score, 2),
                }
            )
    return cards


def main() -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    hexagrams = build_hexagrams()
    tarot = build_tarot_cards()
    if len(hexagrams) != 64:
        raise SystemExit(f"expected 64 hexagrams, got {len(hexagrams)}")
    if len(tarot) != 78:
        raise SystemExit(f"expected 78 tarot cards, got {len(tarot)}")

    (DATA_DIR / "hexagrams.json").write_text(
        json.dumps(hexagrams, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    (DATA_DIR / "tarot_cards.json").write_text(
        json.dumps(tarot, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
